import test from 'node:test';
import assert from 'node:assert/strict';
import { fixture } from './harness.mjs';
import { createService } from '../service.mjs';
import { documentHash } from '../core.mjs';
import { getEditableImageNodes, updateImageNode, updateBlockMarkdown, getEditableTextNodes } from '../../editor/shared/model.mjs';
test('image replacement survives account save, CAS, frozen review and exact approval snapshot', async t => {
  const f = await fixture(); t.after(() => f.db.close());
  const owner = await f.user(), reviewer = await f.user('moderator');
  const service = createService(f.db, { publicationEnabled: true });
  const block = f.guide.blocks.find(item => getEditableImageNodes(item).length);
  const image = getEditableImageNodes(block)[0];
  const document = updateImageNode(f.guide, block.id, image.id, { src: 'https://images.example/reviewed-preset.png', alt: 'Reviewed preset' });
  await service.saveDraft(owner.id, f.guide.id, { document, expectedVersion: 0, baseRevision: 1 });
  const saved = await service.getDraft(owner.id, f.guide.id);
  assert.deepEqual(saved.document, document);
  await assert.rejects(service.saveDraft(owner.id, f.guide.id, { document, expectedVersion: 0, baseRevision: 1 }), e => e.code === 'revision_conflict');
  const submission = await service.submit(owner.id, f.guide.id, { expectedVersion: 1, summary: 'Replace a preset image and describe it' });
  await service.saveDraft(owner.id, f.guide.id, { document: f.guide, expectedVersion: 1, baseRevision: 1 });
  const snapshot = await service.getSubmission(reviewer.id, submission.id);
  assert.deepEqual(snapshot.document, document);
  assert.equal(snapshot.contentHash, documentHash(document));
  await assert.rejects(service.review(owner.id, submission.id, { decision: 'approve', expectedVersion: 1, note: 'Cannot approve my own image' }));
  await service.review(reviewer.id, submission.id, { decision: 'approve', expectedVersion: 1, note: 'Checked source and image description' });
  const row = (await f.db.query('SELECT document,content_hash FROM submissions WHERE id=$1', [submission.id])).rows[0];
  assert.deepEqual(row.document, document);
  assert.equal(row.content_hash, documentHash(document));
  const bad = structuredClone(document); bad.source.attribution = 'Unreviewed provenance rewrite';
  await assert.rejects(service.saveDraft(owner.id, f.guide.id, { document: bad, expectedVersion: 2, baseRevision: 1 }));
  assert.equal((await service.getDraft(owner.id, f.guide.id)).version, 2);
});

test('whole-block Markdown survives hosted save and frozen submission without changing source or permissions', async t => {
  const f = await fixture(); t.after(() => f.db.close());
  const owner = await f.user(), reviewer = await f.user('moderator');
  const service = createService(f.db, { publicationEnabled: true });
  const block = f.guide.blocks.find(item => item.type === 'paragraph' && getEditableTextNodes(item).length);
  const markdown = 'Replacement without the old bullet. **Bold** :dragonbreath:\n\n- A new list item';
  const document = updateBlockMarkdown(f.guide, block.id, markdown);
  await service.saveDraft(owner.id, f.guide.id, { document, expectedVersion: 0, baseRevision: 1 });
  assert.deepEqual((await service.getDraft(owner.id, f.guide.id)).document, document);
  const submission = await service.submit(owner.id, f.guide.id, { expectedVersion: 1, summary: 'Rewrite a complete passage and remove a bullet' });
  await service.saveDraft(owner.id, f.guide.id, { document: f.guide, expectedVersion: 1, baseRevision: 1 });
  const snapshot = await service.getSubmission(reviewer.id, submission.id);
  assert.deepEqual(snapshot.document, document);
  assert.equal(snapshot.contentHash, documentHash(document));
  assert.deepEqual(snapshot.document.source, f.guide.source);
  assert.deepEqual(snapshot.document.blocks.map(item => item.node), f.guide.blocks.map(item => item.node));
  await assert.rejects(service.review(owner.id, submission.id, { decision: 'approve', expectedVersion: 1, note: 'No self approval' }));
  await service.review(reviewer.id, submission.id, { decision: 'approve', expectedVersion: 1, note: 'Checked rendered content and unchanged source' });
  const row = (await f.db.query('SELECT document,content_hash FROM submissions WHERE id=$1', [submission.id])).rows[0];
  assert.deepEqual(row.document, document);
  assert.equal(row.content_hash, documentHash(document));
});
