const target = { ...githubConfig, mode: 'public' };
const denied = code => error => error.code === code;
async function setup(t) {
  const f=await fixture(); t.after(()=>f.db.close());
  const contributor=await f.user(), reviewer=await f.user('moderator'), owner=await f.user('admin');
  const privateService=createService(f.db,{publicationEnabled:true});
  await privateService.saveDraft(contributor.id,f.guide.id,{document:f.changed('Synthetic canonical overlay'),expectedVersion:0,baseRevision:1});
  const legacy=await privateService.submit(contributor.id,f.guide.id,{expectedVersion:1,summary:'Synthetic legacy authority'});
  await privateService.review(reviewer.id,legacy.id,{decision:'approve',expectedVersion:1});
  const info={number:1,branch:'legacy',branchSha:'a'.repeat(40),merged:true,mergeSha:'b'.repeat(40)};
  await createJobRunner(f.db,{ensurePullRequest:async()=>info,reconcile:async()=>({state:'awaiting_deployment',provider:info})}).runOne();
  const current=await privateService.getGuide(f.guide.id);
  const grant={userId:owner.id,discordHash:hash(owner.discordId),guideId:f.guide.id,baseRevision:2,contentHash:current.contentHash,target:publicationTarget(target)};
  const service=createService(f.db,{publicationEnabled:true,repository:f.config.github,bootstrapTarget:target,ownerGrant:grant});
  const pending=await preparePublicBootstrap(f.db,{actorId:owner.id,guideId:f.guide.id,expectedRevision:2,expectedHash:current.contentHash,requestId:randomUUID(),reason:'Synthetic current snapshot request'},target);
  const input={expectedVersion:1,expectedRevision:2,expectedHash:current.contentHash,reason:'Explicit owner authorization for the exact pilot snapshot'};
  const row=async()=> (await f.db.query(`SELECT s.*,${approvalEventsSql('s')} AS approval_events FROM submissions s WHERE id=$1`,[pending.id])).rows[0];
  return {...f,owner,reviewer,contributor,grant,service,pending,input,row,current,legacy};
}
test('only the protected immutable owner identity can approve the exact bootstrap; ordinary review stays independent',async t=>{
  const f=await setup(t), otherAdmin=await f.user('admin');
  for(const user of [f.contributor,f.reviewer,otherAdmin]) await assert.rejects(f.service.approveOwnerSnapshot(user.id,f.pending.id,f.input),e=>e.status===403);
  await assert.rejects(f.service.review(f.owner.id,f.pending.id,{decision:'approve',expectedVersion:1}),denied('self_review_forbidden'));
  for(const input of [{...f.input,expectedHash:'0'.repeat(64)},{...f.input,expectedRevision:3},{...f.input,actorId:f.owner.id}])
    await assert.rejects(f.service.approveOwnerSnapshot(f.owner.id,f.pending.id,input),e=>[400,409].includes(e.status));
  const wrong=createService(f.db,{bootstrapTarget:target,ownerGrant:{...f.grant,discordHash:'0'.repeat(64)}});
  await assert.rejects(wrong.approveOwnerSnapshot(f.owner.id,f.pending.id,f.input),denied('owner_approval_forbidden'));
  const viewed=await f.service.getSubmission(f.owner.id,f.pending.id);
  assert.equal(viewed.publicBootstrap.ownerApprovalAvailable,true);
  assert.equal((await f.service.getSubmission(otherAdmin.id,f.pending.id)).publicBootstrap.ownerApprovalAvailable,undefined);
  const result=await f.service.approveOwnerSnapshot(f.owner.id,f.pending.id,f.input);
  assert.equal(result.status,'approved'); assert.equal(result.publicBootstrap.held,true);
  assert.equal(result.publicBootstrap.approvalPolicy,OWNER_PUBLIC_POLICY);
  assert.equal(result.publicBootstrap.requiresIndependentReview,false);
  const row=await f.row(); assert.equal(row.owner_id,row.reviewer_id); assert.ok(hasValidApproval(row));
  assert.equal(ownerApprovalEvidence(row).actor_id,f.owner.id);
  await verifyPublicBootstrap(f.db,row,target);
  const before=(await f.db.query('SELECT * FROM publication_jobs WHERE submission_id=$1',[f.pending.id])).rows[0];
  let calls=0;
  assert.deepEqual(await createJobRunner(f.db,{ensurePullRequest:async()=>{calls++;}}, {target:{mode:'private'}}).runOne({submissionId:f.pending.id}),{state:'idle'});
  assert.equal(calls,0); assert.deepEqual((await f.db.query('SELECT * FROM publication_jobs WHERE submission_id=$1',[f.pending.id])).rows[0],before);
  assert.equal((await f.db.query('SELECT count(*) FROM public_publications')).rows[0].count,0);
});
