test('hosted owner approval requires session, CSRF and exact protected grant and never dispatches',async t=>{
  const f=await setup(t); let calls=0;
  const handler=createHandler({db:f.db,config:{...f.config,publicBootstrap:target,ownerPublicApproval:f.grant},publisher:{ensurePullRequest:async()=>{calls++;}}});
  const path=`submissions/${f.pending.id}/owner-approval`;
  for (const user of [undefined,f.contributor,f.reviewer]) assert.equal((await handler(request('admin/account-binding',{user}))).status,user?403:401);
  const binding=await (await handler(request('admin/account-binding',{user:f.owner}))).json();
  assert.deepEqual(binding.binding,{userId:f.owner.id,discordHash:hash(f.owner.discordId)});
  assert.equal((await handler(request(path,{method:'POST',body:f.input}))).status,401);
  assert.equal((await handler(request(path,{method:'POST',body:f.input,user:f.owner,headers:{'X-CSRF-Token':'wrong'}}))).status,403);
  assert.equal((await handler(request(path,{method:'POST',body:f.input,user:f.owner,origin:'https://attacker.example'}))).status,403);
  assert.equal((await handler(request(path,{method:'POST',body:f.input,user:f.reviewer}))).status,403);
  const response=await handler(request(path,{method:'POST',body:f.input,user:f.owner}));
  assert.equal(response.status,200); assert.equal((await response.json()).submission.status,'approved'); assert.equal(calls,0);
});
test('a freshly owner-authorized immutable snapshot reaches only its sanitized proof PR using fixtures',async t=>{
  const f=await setup(t); await f.service.approveOwnerSnapshot(f.owner.id,f.pending.id,f.input);
  const row=await f.row(), fake=githubFake(row); fake.setPrivate(false);
  fake.commitOnMain({[`editor/content/${f.guide.id}.json`]:f.guide,[`content/guides/${f.guide.id}.json`]:f.current.document});
  const originals=(await f.db.query('SELECT guide_id,document FROM guide_revisions WHERE revision=1')).rows;
  fake.commitOnMain(Object.fromEntries(originals.map(r=>[`editor/content/${r.guide_id}.json`,r.document])));
  fake.commitOnMain({'editor/content/catalog.json':originals.map(r=>({id:r.guide_id,file:`${r.guide_id}.json`}))});
  const provider=createPublisher(target,f.db,fake), runner=createJobRunner(f.db,provider,{origin:f.config.origin});
  assert.equal((await runner.runOne({submissionId:f.pending.id})).state,'awaiting_merge');
  const pull=fake.pulls[0], head=fake.commits.get(pull.head.sha), parent=fake.commits.get(head.parents[0].sha);
  assert.deepEqual(Object.keys(head.files).filter(path=>head.files[path]!==parent.files[path]),[`content/publications/${f.guide.id}.json`]);
  const writes=JSON.stringify(fake.calls.filter(call=>call.method==='POST'&&!call.path.includes('/access_tokens')).map(call=>call.body));
  for(const privateValue of [f.owner.id,f.owner.discordId,f.grant.discordHash,row.id,f.input.reason,OWNER_PUBLIC_POLICY]) assert.ok(!writes.includes(privateValue));
  const commit=fake.merge(); await runner.wake();
  assert.equal((await runner.runOne({submissionId:f.pending.id})).state,'awaiting_deployment');
  assert.equal((await f.service.getGuide(f.guide.id)).revision,3);
  assert.deepEqual((await f.service.getGuide(f.guide.id)).document,f.current.document);
  const proof=publicProof(row), proofKey=publicProofKey(proof), contents=fake.fileContents(commit);
  const sourceFiles=Object.entries(fake.commits.get(commit).files).map(([path,sha])=>({path,sha,size:Buffer.byteLength(contents[path])}));
  const published=new Map([[f.guide.id,{document:row.document,contentHash:row.content_hash,proof,proofKey}]]);
  assert.equal((await verifyPublicBuildGate(f.db,published,{expectedBaselines:new Map(originals.map(r=>[r.guide_id,r.document])),repository:`${target.owner}/${target.repo}`,baseBranch:'main',commit,sourceFiles,verifyCommit:(sha,entries,opts)=>provider.verifyBuildCommit(sha,entries,opts)})).verifiedCount,1);
  fake.release({schemaVersion:2,commit,guides:{[f.guide.id]:{proofKey,contentHash:row.content_hash}}});
  await runner.wake(); assert.equal((await runner.runOne({submissionId:f.pending.id})).state,'published');
  assert.equal((await f.db.query('SELECT target FROM publication_jobs WHERE submission_id=$1',[f.legacy.id])).rows[0].target.mode,'private');
});
test('explicit owner dispatch uses only the approved owner job and org provider; private cron stays isolated',async t=>{
  const f=await setup(t); let calls=0, privateCalls=0;
  const ownerPublisher={ensurePullRequest:async row=>{calls++;assert.equal(row.id,f.pending.id);return {number:2,branchSha:'c'.repeat(40)};},reconcile:async()=>({state:'awaiting_merge',provider:{number:2,branchSha:'c'.repeat(40)}})};
  const handler=createHandler({db:f.db,config:{...f.config,publicBootstrap:target,ownerPublicApproval:f.grant,ownerPublicGithub:target},publisher:{ensurePullRequest:async()=>{privateCalls++;}},ownerPublisher});
  const path=`submissions/${f.pending.id}/owner-publication`;
  const send=(user,input)=>handler(request(path,{method:'POST',user,body:input}));
  assert.equal((await send(f.owner,{expectedVersion:1,expectedRevision:2,expectedHash:f.current.contentHash})).status,403);
  await f.service.approveOwnerSnapshot(f.owner.id,f.pending.id,f.input);
  const input={expectedVersion:2,expectedRevision:2,expectedHash:f.current.contentHash};
  assert.equal((await send(f.reviewer,input)).status,403);
  assert.equal((await send(await f.user('admin'),input)).status,403);
  assert.equal((await send(f.owner,{...input,expectedHash:'0'.repeat(64)})).status,409);
  assert.equal((await send(f.owner,input)).status,200);
  assert.equal(calls,1); assert.equal(privateCalls,0);
});
