import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { getEditableImageNodes, updateImageNode, getEditableTextNodes, updateTextNode } from '../shared/model.mjs';
import { changedBlocks, changedFields, conflictPlan, resolveConflict } from '../src/document.mjs';
import { reviewChangesHTML, changePreviewHTML } from '../src/review-changes.mjs';
const baseline = JSON.parse(await readFile(new URL('../content/arch-glacor-basic.json', import.meta.url)));
const block = baseline.blocks.find(item => getEditableImageNodes(item).length);
const image = getEditableImageNodes(block)[0];
const replace = (document, src, alt = image.alt) => updateImageNode(document, block.id, image.id, { src, alt });
test('an image-only edit is reviewable even when its description stays the same', () => {
  const changed = replace(baseline, 'https://images.example/preset.png');
  const fields = changedFields(baseline, changed);
  assert.equal(fields.length, 1);
  assert.equal(fields[0].kind, 'image');
  assert.equal(changedBlocks(baseline, changed).length, 1);
  const html = reviewChangesHTML(baseline, changed);
  assert.match(html, /<h3>Image<\/h3>/);
  assert.match(html, /review-image-change/);
  assert.match(html, /https:\/\/images.example\/preset.png/);
  assert.match(html, /Before/);
  assert.match(html, /After/);
  const undo = replace(changed, image.src);
  assert.equal(changedFields(baseline, undo).length, 0);
});
test('description-only changes stay visible and cannot introduce review HTML', () => {
  const changed = replace(baseline, image.src, '<img src=x onerror=alert(1)>');
  const fields = changedFields(baseline, changed);
  assert.equal(fields.length, 1);
  const html = changePreviewHTML(fields[0], fields[0].after);
  assert.match(html, /&lt;img src=x onerror=alert\(1\)&gt;/);
  assert.doesNotMatch(html, /<img src=x/);
});
test('same-image conflicts require a choice and independent text changes merge', () => {
  const local = replace(baseline, 'https://images.example/local.png');
  const remote = replace(baseline, 'https://images.example/remote.png');
  const plan = conflictPlan(baseline, local, remote);
  assert.equal(plan.length, 1);
  assert.equal(plan[0].overlap, true);
  assert.deepEqual(resolveConflict(remote, plan), remote);
  assert.deepEqual(resolveConflict(remote, plan, { [image.id]: 'local' }), local);
  const textBlock = baseline.blocks.find(item => getEditableTextNodes(item).length);
  const text = getEditableTextNodes(textBlock)[0];
  const otherEdit = updateTextNode(baseline, textBlock.id, text.id, 'Independent wording');
  const merged = resolveConflict(otherEdit, conflictPlan(baseline, local, otherEdit));
  assert.equal(changedFields(baseline, merged).length, 2);
  assert.equal(getEditableImageNodes(merged.blocks.find(item => item.id === block.id))[0].src, 'https://images.example/local.png');
  assert.equal(conflictPlan(baseline, local, local)[0].overlap, false);
});
