import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const host=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const directory=path.join(host,'copy-button-ports');
const plan=JSON.parse(fs.readFileSync(path.join(host,'main-guides/corpus-plan.json')));
const page=plan.pages.find(p=>p.title==='PvME/Vorago/Vorago — Overview');
const published=JSON.parse(fs.readFileSync(path.join(host,'main-guides/published-revisions.json'))).pages.find(p=>p.title===page.title);
const sandbox={module:{exports:{}},URL};
vm.runInNewContext(fs.readFileSync(path.join(host,'presentation/module/modules/wiki-export.js'),'utf8'),sandbox);
const source=fs.readFileSync(path.join(host,'main-guides',page.file),'utf8');
const result=sandbox.module.exports.convertRevision(source,{title:page.title,displayTitle:page.nativeTitle,revisionId:published.revision,timestamp:published.timestamp,source:page.source,revisionUrl:published.permalink},JSON.parse(fs.readFileSync(path.join(host,'presentation/module/modules/navigation.json'))),{},{},JSON.parse(fs.readFileSync(path.join(directory,'vorago-asset-resolver.json'))));
const {text,...report}=result;let cursor=0;const missing=[];
for(const node of source.matchAll(/<nowiki>[\s\S]*?<\/nowiki>/g)){if(/^<nowiki>\s*<\/nowiki>$/.test(node[0]))continue;const at=text.indexOf(node[0],cursor);if(at<0)missing.push(node[0]);else cursor=at+node[0].length;}
report.literalNodesUnchangedInOrder=missing.length===0;
report.literalNodeCount=[...source.matchAll(/<nowiki>[\s\S]*?<\/nowiki>/g)].filter(n=>!/^<nowiki>\s*<\/nowiki>$/.test(n[0])).length;
if(missing.length)throw Error('Original literal source text was lost or reordered');
fs.writeFileSync(path.join(directory,'pilot-vorago.wiki'),text);
fs.writeFileSync(path.join(directory,'pilot-vorago-export.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({characters:text.length,ready:result.readyToPublish,imageReady:result.imageReady,inlineMediaReady:result.inlineMediaReady,literalNodes:report.literalNodeCount,wordNodesMatch:report.literalNodesUnchangedInOrder,media:result.mediaCoverage,notices:result.mediaNotices}));
